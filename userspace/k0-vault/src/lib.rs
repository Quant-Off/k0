//! K0 키 볼트(서명 오라클) 크레이트입니다.
//!
//! # Features
//! 격리된 태스크 하나(볼트)가 서명 키를 쥐고, 다른 태스크(클라이언트)는 IPC로
//! 서명과 공개키만 받아 갑니다. 이 크레이트는 그 프로토콜([proto]), 요청을
//! 처리하는 상태 기계([server]), 암호 구현을 감싼 경계([provider])를 담습니다.
//! 시스템 콜은 쓰지 않습니다. 메시지를 주고받는 루프는 이 크레이트를 링크한
//! 태스크의 몫이라서, 상태 기계와 암호 경계는 호스트에서 그대로 테스트됩니다.
//!
//! 볼트의 코드는 루트 태스크 이미지에 들어가고(부팅 뒤에 코드를 적재하지
//! 않음), 격리 태스크의 주소 공간에는 이미지의 `.data`와 `.bss`가 없습니다.
//! 그래서 이 크레이트는 할당도 가변 static도 쓰지 않습니다.
//!
//! 알고리즘은 Cargo feature로 더합니다. `ed25519`를 주면 Ed25519(SHA-512를
//! 쓰는 PureEdDSA, FIPS 186-5와 RFC 8032)가 들어갑니다. 구현은 vendor에 둔
//! `ed25519-dalek`이고 어떤 인증도 받지 않았습니다. 키는 승인된 난수
//! 발생기가 아니라 커널이 넘긴 부트 시드에서 나옵니다.
//!
//! # Errors
//! 시작 시 자가 시험이나 키 생성 뒤의 쌍 일치 시험이 실패하면 볼트는 오류
//! 상태가 되어 상태 조회 말고는 모든 서비스를 거부합니다.

